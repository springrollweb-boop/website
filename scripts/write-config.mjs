// Writes site/js/config.js from environment variables.
// Vercel runs this on every deploy (see vercel.json). Locally it also reads .env.local.
//   SUPABASE_URL       e.g. https://abcd.supabase.co
//   SUPABASE_ANON_KEY  the public anon key (eyJ...) or publishable key (sb_publishable_...)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// local convenience: load .env.local if present (never committed)
const envFile = path.join(root, '.env.local');
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
}

const url = (process.env.SUPABASE_URL || '').trim().replace(/\/$/, '');
const key = (process.env.SUPABASE_ANON_KEY || '').trim();
const fail = (msg) => { console.error('write-config: ' + msg); process.exit(1); };

if (!url || !key) fail('SUPABASE_URL and SUPABASE_ANON_KEY must be set (Vercel > Project > Settings > Environment Variables).');
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) fail('SUPABASE_URL should look like https://xxxx.supabase.co');

// refuse anything that is not a public key, so a secret can never be published by mistake
if (/^sb_secret_/.test(key)) fail('SUPABASE_ANON_KEY is a secret key. Use the anon or publishable key instead.');
if (/^eyJ/.test(key)) {
  let role = '';
  try { role = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString()).role; } catch (e) { fail('SUPABASE_ANON_KEY is not a valid key.'); }
  if (role !== 'anon') fail(`SUPABASE_ANON_KEY has role "${role}". Only the anon key may be used; never the service_role key.`);
} else if (!/^sb_publishable_/.test(key)) {
  fail('SUPABASE_ANON_KEY should start with eyJ (anon) or sb_publishable_.');
}

const out = `/* Generated by scripts/write-config.mjs from environment variables. Do not edit or commit. */
window.SRS_CONFIG = {
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(key)}
};
`;
fs.writeFileSync(path.join(root, 'site/js/config.js'), out);
console.log('write-config: wrote site/js/config.js for ' + url);
